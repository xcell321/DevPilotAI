import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import runtimePaths from '../shared/runtime-paths.cjs';

const { resolveRuntimeDir, runtimeFileFor } = runtimePaths;

const root = path.resolve(import.meta.dirname, '..');

try {
  process.loadEnvFile(path.join(root, '.env'));
} catch {
  // .env is optional.
}

function getFreePort() {
  return new Promise((resolve, reject) => {
    const probe = net.createServer();
    probe.unref();
    probe.on('error', reject);
    probe.listen(0, '127.0.0.1', () => {
      const address = probe.address();
      const port = typeof address === 'object' && address ? address.port : 0;
      probe.close(() => resolve(port));
    });
  });
}

async function waitForRuntimeFile(file, expectedPort, timeoutMs = 25000) {
  const started = Date.now();
  while (Date.now() - started < timeoutMs) {
    try {
      const runtime = JSON.parse(fs.readFileSync(file, 'utf8'));
      if (runtime.port === expectedPort) return runtime;
    } catch {
      // The server has not written its runtime file yet.
    }
    await new Promise((resolve) => setTimeout(resolve, 150));
  }
  throw new Error(`Server did not publish its runtime file at ${file}`);
}

function killTree(pid) {
  if (!pid) return;
  if (process.platform === 'win32') {
    spawnSync('taskkill', ['/pid', String(pid), '/T', '/F'], { stdio: 'ignore' });
    return;
  }
  try {
    process.kill(-pid, 'SIGTERM');
  } catch {
    try {
      process.kill(pid, 'SIGTERM');
    } catch {
      // Process already exited.
    }
  }
}

function startNpm(args, env) {
  const npmCli = process.env.npm_execpath;
  const options = {
    cwd: root,
    env: { ...process.env, ...env },
    stdio: 'inherit',
  };

  if (npmCli) {
    return spawn(process.execPath, [npmCli, ...args], options);
  }

  if (process.platform === 'win32') {
    return spawn('cmd.exe', ['/d', '/s', '/c', `npm ${args.join(' ')}`], options);
  }

  return spawn('npm', args, options);
}

const serverPort = await getFreePort();
const webPort = await getFreePort();
const runtimeDir = resolveRuntimeDir(root);
const runtimeFile = runtimeFileFor(root);

fs.rmSync(runtimeFile, { force: true });

const server = startNpm(['run', 'dev', '-w', 'server'], {
  DEVPILOT_PORT: String(serverPort),
  DEVPILOT_RUNTIME_DIR: runtimeDir,
});
let web = null;
let shuttingDown = false;

function shutdown(exitCode = 0) {
  if (shuttingDown) return;
  shuttingDown = true;
  killTree(web?.pid);
  killTree(server.pid);
  fs.rmSync(runtimeFile, { force: true });
  process.exitCode = exitCode;
}

server.on('exit', (code) => {
  if (!shuttingDown) {
    console.error(`\nDevPilot server stopped (exit ${code ?? 'unknown'}).`);
    shutdown(code ?? 1);
  }
});

for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => shutdown(0));
}

try {
  const runtime = await waitForRuntimeFile(runtimeFile, serverPort);
  web = startNpm(['run', 'dev', '-w', 'apps/web'], {
    DEVPILOT_SERVER_ORIGIN: runtime.origin,
    DEVPILOT_WEB_PORT: String(webPort),
    DEVPILOT_RUNTIME_DIR: runtimeDir,
  });

  web.on('exit', (code) => {
    if (!shuttingDown) {
      console.error(`\nDevPilot web server stopped (exit ${code ?? 'unknown'}).`);
      shutdown(code ?? 1);
    }
  });

  console.log('');
  console.log('DevPilot AI (local-first)');
  console.log(`  Server: ${runtime.origin}`);
  console.log(`  Web:    http://127.0.0.1:${webPort}`);
  console.log(`  Local API token: generated by the server in ${runtimeFile}`);
  console.log('');
} catch (error) {
  console.error(error.message);
  shutdown(1);
}
